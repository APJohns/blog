import { useEffect, useImperativeHandle, useRef, type ComponentPropsWithRef, type Ref } from 'react';

export interface ClockRef {
  reset: () => void;
}

interface ClockProps {
  dilationFactor?: number;
  elapsedSeconds: number;
  timezone?: string;
  ref?: Ref<ClockRef>;
}

export default function Clock({ dilationFactor = 1, elapsedSeconds, timezone, ref }: ClockProps) {
  const secondsHandRef = useRef<HTMLDivElement>(null);
  const minutesHandRef = useRef<HTMLDivElement>(null);
  const hoursHandRef = useRef<HTMLDivElement>(null);

  useImperativeHandle(ref, () => ({
    reset: () => {
      if (secondsHandRef.current && minutesHandRef.current && hoursHandRef.current) {
        const animations = [
          ...secondsHandRef.current.getAnimations(),
          ...minutesHandRef.current.getAnimations(),
          ...hoursHandRef.current.getAnimations(),
        ];
        animations.forEach((animation) => {
          animation.cancel();
          animation.play();
        });
      }
    },
  }));

  return (
    <figure className="clock-figure">
      <div className="clock">
        <SVGClock />
        {timezone && <div className="timezone">{timezone}</div>}
        <div
          ref={secondsHandRef}
          className="hand second-hand"
          style={{
            animationDuration: `${60 / dilationFactor}s`,
          }}
        />
        <div
          ref={minutesHandRef}
          className="hand minute-hand"
          style={{
            animationDuration: `${(60 * 60) / dilationFactor}s`,
          }}
        />
        <div
          ref={hoursHandRef}
          className="hand hour-hand"
          style={{
            animationDuration: `${(60 * 60 * 12) / dilationFactor}s`,
          }}
        />
      </div>
      <figcaption className="visually-hidden">
        {elapsedSeconds} seconds elapsed
        {timezone ? `on ${timezone}` : ''}.
      </figcaption>
    </figure>
  );
}

